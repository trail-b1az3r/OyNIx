#!/usr/bin/env bash
# Build an Arch Linux / pacman package (.pkg.tar.zst) with the bundled
# Qt 6.12 runtime. Works on any Linux: uses only bsdtar + zstd, writing the
# same metadata makepkg does (.PKGINFO, .BUILDINFO, .MTREE).
#   usage: scripts/build-pkg.sh [version]      → target/pkg/oynix-<ver>-1-x86_64.pkg.tar.zst
set -euo pipefail
cd "$(dirname "$0")/.."
for t in bsdtar zstd; do command -v $t >/dev/null || { echo "$t is required (apt install libarchive-tools zstd / pacman -S libarchive zstd)" >&2; exit 1; }; done
VERSION="${1:-$(grep -m1 '^version' Cargo.toml | cut -d'"' -f2)}"
VERSION="${VERSION#v}"
export OYNIX_VERSION="$VERSION"
PKGVER="${VERSION//-/_}"           # pacman versions may not contain '-'
PKGREL="${PKGREL:-1}"
ARCH="$(uname -m)"
ROOT="$PWD/target/pkg/root"
OUT="$PWD/target/pkg/oynix-${PKGVER}-${PKGREL}-${ARCH}.pkg.tar.zst"

scripts/stage.sh "$ROOT" usr/share/licenses/oynix/LICENSE

DEPENDS=(glibc gcc-libs libglvnd vulkan-icd-loader libxkbcommon libxkbcommon-x11 xcb-util-cursor
         xcb-util-wm xcb-util-keysyms xcb-util-image xcb-util-renderutil nss libxcomposite
         libxdamage libxrandr libxtst fontconfig dbus alsa-lib)
SIZE=$(du -sb "$ROOT/usr" | cut -f1)
NOW=$(date +%s)
{
  echo "# Generated by OyNIx scripts/build-pkg.sh"
  echo "pkgname = oynix"
  echo "pkgbase = oynix"
  echo "pkgver = ${PKGVER}-${PKGREL}"
  echo "pkgdesc = Fast, private web browser (Rust + QML, Qt 6.12) with Chrome/Firefox extension support"
  echo "url = https://github.com/trail-b1az3r/OyNIx"
  echo "builddate = $NOW"
  echo "packager = OyNIx build script"
  echo "size = $SIZE"
  echo "arch = $ARCH"
  echo "license = MIT"
  echo "provides = oynix"
  for d in "${DEPENDS[@]}"; do echo "depend = $d"; done
  echo "optdepend = mesa-vulkan-drivers: Vulkan rendering on Mesa GPUs"
  echo "optdepend = polkit: install OyNIx updates from the browser"
} > "$ROOT/.PKGINFO"
{
  echo "format = 2"
  echo "pkgname = oynix"
  echo "pkgbase = oynix"
  echo "pkgver = ${PKGVER}-${PKGREL}"
  echo "pkgarch = $ARCH"
  echo "builddate = $NOW"
  echo "packager = OyNIx build script"
  echo "builddir = /build"
  echo "startdir = /build"
  echo "buildenv = !distcc"
  echo "options = !strip"
} > "$ROOT/.BUILDINFO"

cd "$ROOT"
# .MTREE lists every file with checksums so pacman can verify the install.
LANG=C bsdtar -czf .MTREE --format=mtree \
  --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' \
  .PKGINFO .BUILDINFO usr
LANG=C bsdtar -cf - --uid 0 --gid 0 --uname root --gname root .MTREE .PKGINFO .BUILDINFO usr \
  | zstd -q -T0 -19 -f -o "$OUT"
cd - >/dev/null
ls -lh "$OUT"
